a = 3 # 00000011 / 0011
b = 7 # 00000111 / 0111
print(a & b) # 1+0 / 0+1  / 0+0=> 0 ||| 1+1 => 1
print(a | b) # 0+0 => 0 ||| 1+1 / 1+0 / 0+1 => 1
print(a ^ b) # 0+0 / 1+1 => 0 ||| 1+0 / 0+1 => 1
